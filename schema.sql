-- ==============================================================================
-- GOMEX DISTRIBUIDORA · BANCO DE DADOS SUPABASE
-- Tabela de Check-lists de Veículos & Controle de Frota
-- ==============================================================================

create table if not exists public.veiculo_checklists (
  id bigint generated by default as identity primary key,
  numero text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  
  -- 1. Identificação
  veiculo text not null,
  veiculo_outro text,
  placa text not null,
  km numeric,
  motorista text not null,
  data date not null default current_date,
  hora text,
  tipo text not null, -- 'Saída', 'Retorno', 'Periódica'
  combustivel text,   -- 'Reserva', '1/4', '1/2', '3/4', 'Cheio'
  rev_ult_km numeric,
  rev_ult_data date,
  rev_prox_km numeric,
  rev_prox_data date,
  
  -- 2. Avarias
  avarias jsonb default '[]'::jsonb,
  sem_avarias boolean default false,
  
  -- 3. Pneus
  pneus jsonb default '{}'::jsonb,
  pneu_dano text, -- 'Não', 'Sim'
  
  -- 4. Itens de Verificação
  itens jsonb default '[]'::jsonb,
  extintor_validade text,
  thermo_temp numeric,
  outro_item text,
  
  -- 5. Observações & Liberação
  obs text,
  condicao_motorista text, -- 'Apto', 'Cansado'
  liberacao text not null, -- 'Liberado', 'Ressalva', 'Não liberado'
  
  -- 6. Assinaturas (Base64 PNG/JPEG)
  ass_motorista text,
  ass_vistoriador text,
  ass_responsavel text,
  
  -- Metadados do SaaS
  status text default 'concluido'
);

-- Índices para buscas rápidas no SaaS
create index if not exists idx_veiculo_checklists_placa on public.veiculo_checklists(placa);
create index if not exists idx_veiculo_checklists_data on public.veiculo_checklists(data desc);
create index if not exists idx_veiculo_checklists_motorista on public.veiculo_checklists(motorista);
create index if not exists idx_veiculo_checklists_liberacao on public.veiculo_checklists(liberacao);

-- Habilitar RLS (Row Level Security)
alter table public.veiculo_checklists enable row level security;

-- Políticas de acesso público (Leitura e Inserção para o app Gomex)
drop policy if exists "Permitir leitura publica de checklists" on public.veiculo_checklists;
create policy "Permitir leitura publica de checklists"
  on public.veiculo_checklists for select
  using (true);

drop policy if exists "Permitir insercao anonima de checklists" on public.veiculo_checklists;
create policy "Permitir insercao anonima de checklists"
  on public.veiculo_checklists for insert
  with check (true);

drop policy if exists "Permitir atualizacao anonima de checklists" on public.veiculo_checklists;
create policy "Permitir atualizacao anonima de checklists"
  on public.veiculo_checklists for update
  using (true);

-- ==============================================================================
-- Sequência Oficial de Numeração de Vistorias
-- ==============================================================================
create sequence if not exists public.checklist_numero_seq start with 1 increment by 1;

create or replace function public.proximo_numero_checklist()
returns text as $$
begin
  return lpad(nextval('public.checklist_numero_seq')::text, 6, '0');
end;
$$ language plpgsql;

alter table public.veiculo_checklists 
  alter column numero set default public.proximo_numero_checklist();

create or replace function public.trg_set_checklist_numero()
returns trigger as $$
begin
  if NEW.numero is null or NEW.numero = '' or NEW.numero = 'AUTO' then
    NEW.numero := public.proximo_numero_checklist();
  end if;
  return NEW;
end;
$$ language plpgsql;

drop trigger if exists trg_veiculo_checklists_numero on public.veiculo_checklists;
create trigger trg_veiculo_checklists_numero
  before insert on public.veiculo_checklists
  for each row
  execute function public.trg_set_checklist_numero();

